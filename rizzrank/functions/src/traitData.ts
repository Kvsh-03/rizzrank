/** All trait category keys. */
export const TRAIT_CATEGORIES = Object.keys(TRAIT_DATA) as (keyof typeof TRAIT_DATA)[];

/** Picks one random value from each trait category. */
export function pickRandomTraits(): Record<string, string> {
  const result: Record<string, string> = {};
  for (const category of TRAIT_CATEGORIES) {
    const values = TRAIT_DATA[category];
    result[category] = values[Math.floor(Math.random() * values.length)];
  }
  return result;
}
